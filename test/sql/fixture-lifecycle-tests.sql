begin;
set local statement_timeout='25s';
create temp table lifecycle_results(test text,passed boolean) on commit drop;
grant insert,select on lifecycle_results to authenticated,anon;
do $$
declare
 c uuid:=gen_random_uuid(); d uuid:=gen_random_uuid();
 a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); pa uuid; pb uuid;
 v uuid; w uuid; f uuid; g uuid; h uuid; s uuid; t uuid; u uuid;
 denied boolean; n bigint; baseline bigint; replacement uuid; j jsonb;
begin
 if exists(select 1 from cron.job where active) then raise exception 'Disable cron before test'; end if;
 select count(*) into baseline from public.notification_queue;
 insert into public.clubs(id,name) values(c,'ROLLBACK publication own'),(d,'ROLLBACK publication foreign');
 insert into auth.users(id,email,raw_user_meta_data,raw_app_meta_data) values
 (a,a::text||'@example.invalid','{"display_name":"Publication admin"}','{}'),
 (b,b::text||'@example.invalid','{"display_name":"Publication foreign reserve"}','{}');
 select id into pa from public.member_profiles where user_id=a;
 select id into pb from public.member_profiles where user_id=b;
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(c,pa,'admin',true),(d,pb,'member',true);
 insert into public.venues(club_id,name,is_home_venue) values(c,'Rollback own venue',false) returning id into v;
 insert into public.venues(club_id,name,is_home_venue) values(d,'Rollback foreign venue',false) returning id into w;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '30 days',false,v,1,4) returning id into f;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '31 days',false,v,1,4) returning id into h;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(d,now()+interval '32 days',false,w,1,4) returning id into g;
 insert into public.team_selections(fixture_id) values(f) returning id into s;
 insert into public.team_selections(fixture_id) values(g) returning id into t;
 insert into public.team_selections(fixture_id) values(h) returning id into u;
 insert into public.team_selection_members(team_selection_id,member_profile_id,role,is_selected) values(s,pa,'reserve',true),(t,pb,'reserve',true);
 update public.fixtures set cancelled_at=now(),cancellation_reason='Rollback setup' where id=h;
 reset role;
 update public.club_memberships set role='member',is_active=true where club_id=c and member_profile_id=pa;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 denied:=false; begin perform public.cancel_fixture_safe(f,'Rollback test'); exception when raise_exception then denied:=sqlerrm='You do not have permission to cancel this fixture.'; end;
 insert into lifecycle_results values('cancel_fixture_safe member denied',denied);
 denied:=false; begin perform public.fixture_deletion_preview(f); exception when raise_exception then denied:=sqlerrm='Not authorized to delete this fixture'; end;
 insert into lifecycle_results values('fixture_deletion_preview member denied',denied);
 denied:=false; begin perform public.delete_fixture(f,'Rollback test'); exception when raise_exception then denied:=sqlerrm='Not authorized to delete this fixture'; end;
 insert into lifecycle_results values('delete_fixture with reason member denied',denied);
 denied:=false; begin perform public.delete_fixture(f); exception when raise_exception then denied:=sqlerrm='Not authorized to delete this fixture'; end;
 insert into lifecycle_results values('delete_fixture wrapper member denied',denied);
 denied:=false; begin perform public.reschedule_cancelled_fixture_safe(h,now()+interval '40 days',now()+interval '40 days 2 hours'); exception when raise_exception then denied:=sqlerrm='You do not have permission to reschedule this fixture.'; end;
 insert into lifecycle_results values('reschedule_cancelled_fixture_safe member denied',denied);
 reset role;
 update public.club_memberships set role='guest',is_active=true where club_id=c and member_profile_id=pa;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 denied:=false; begin perform public.cancel_fixture_safe(f,'Rollback test'); exception when raise_exception then denied:=sqlerrm='You do not have permission to cancel this fixture.'; end;
 insert into lifecycle_results values('cancel_fixture_safe guest denied',denied);
 denied:=false; begin perform public.fixture_deletion_preview(f); exception when raise_exception then denied:=sqlerrm='Not authorized to delete this fixture'; end;
 insert into lifecycle_results values('fixture_deletion_preview guest denied',denied);
 denied:=false; begin perform public.delete_fixture(f,'Rollback test'); exception when raise_exception then denied:=sqlerrm='Not authorized to delete this fixture'; end;
 insert into lifecycle_results values('delete_fixture with reason guest denied',denied);
 denied:=false; begin perform public.delete_fixture(f); exception when raise_exception then denied:=sqlerrm='Not authorized to delete this fixture'; end;
 insert into lifecycle_results values('delete_fixture wrapper guest denied',denied);
 denied:=false; begin perform public.reschedule_cancelled_fixture_safe(h,now()+interval '40 days',now()+interval '40 days 2 hours'); exception when raise_exception then denied:=sqlerrm='You do not have permission to reschedule this fixture.'; end;
 insert into lifecycle_results values('reschedule_cancelled_fixture_safe guest denied',denied);
 reset role;
 update public.club_memberships set role='admin',is_active=false where club_id=c and member_profile_id=pa;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 denied:=false; begin perform public.cancel_fixture_safe(f,'Rollback test'); exception when raise_exception then denied:=sqlerrm='You do not have permission to cancel this fixture.'; end;
 insert into lifecycle_results values('cancel_fixture_safe inactive admin denied',denied);
 denied:=false; begin perform public.fixture_deletion_preview(f); exception when raise_exception then denied:=sqlerrm='Not authorized to delete this fixture'; end;
 insert into lifecycle_results values('fixture_deletion_preview inactive admin denied',denied);
 denied:=false; begin perform public.delete_fixture(f,'Rollback test'); exception when raise_exception then denied:=sqlerrm='Not authorized to delete this fixture'; end;
 insert into lifecycle_results values('delete_fixture with reason inactive admin denied',denied);
 denied:=false; begin perform public.delete_fixture(f); exception when raise_exception then denied:=sqlerrm='Not authorized to delete this fixture'; end;
 insert into lifecycle_results values('delete_fixture wrapper inactive admin denied',denied);
 denied:=false; begin perform public.reschedule_cancelled_fixture_safe(h,now()+interval '40 days',now()+interval '40 days 2 hours'); exception when raise_exception then denied:=sqlerrm='You do not have permission to reschedule this fixture.'; end;
 insert into lifecycle_results values('reschedule_cancelled_fixture_safe inactive admin denied',denied);
 reset role;
 update public.club_memberships set role='admin',is_active=true where club_id=c and member_profile_id=pa;
 update public.club_memberships set role='admin' where club_id=d and member_profile_id=pb;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated')::text,true);
 set local role authenticated;
 denied:=false; begin perform public.cancel_fixture_safe(f,'Rollback test'); exception when raise_exception then denied:=sqlerrm='You do not have permission to cancel this fixture.'; end;
 insert into lifecycle_results values('cancel_fixture_safe foreign admin denied',denied);
 denied:=false; begin perform public.fixture_deletion_preview(f); exception when raise_exception then denied:=sqlerrm='Not authorized to delete this fixture'; end;
 insert into lifecycle_results values('fixture_deletion_preview foreign admin denied',denied);
 denied:=false; begin perform public.delete_fixture(f,'Rollback test'); exception when raise_exception then denied:=sqlerrm='Not authorized to delete this fixture'; end;
 insert into lifecycle_results values('delete_fixture with reason foreign admin denied',denied);
 denied:=false; begin perform public.delete_fixture(f); exception when raise_exception then denied:=sqlerrm='Not authorized to delete this fixture'; end;
 insert into lifecycle_results values('delete_fixture wrapper foreign admin denied',denied);
 denied:=false; begin perform public.reschedule_cancelled_fixture_safe(h,now()+interval '40 days',now()+interval '40 days 2 hours'); exception when raise_exception then denied:=sqlerrm='You do not have permission to reschedule this fixture.'; end;
 insert into lifecycle_results values('reschedule_cancelled_fixture_safe foreign admin denied',denied);
 reset role;
 update public.club_memberships set role='admin',is_active=true where club_id=c and member_profile_id=pa;
 perform set_config('request.jwt.claims','{}',true);
 set local role authenticated;
 denied:=false; begin perform public.cancel_fixture_safe(f,'Rollback test'); exception when raise_exception then denied:=sqlerrm='Not signed in.'; end;
 insert into lifecycle_results values('cancel_fixture_safe missing identity denied',denied);
 denied:=false; begin perform public.fixture_deletion_preview(f); exception when raise_exception then denied:=sqlerrm='Authentication required'; end;
 insert into lifecycle_results values('fixture_deletion_preview missing identity denied',denied);
 denied:=false; begin perform public.delete_fixture(f,'Rollback test'); exception when raise_exception then denied:=sqlerrm='Authentication required'; end;
 insert into lifecycle_results values('delete_fixture with reason missing identity denied',denied);
 denied:=false; begin perform public.delete_fixture(f); exception when raise_exception then denied:=sqlerrm='Authentication required'; end;
 insert into lifecycle_results values('delete_fixture wrapper missing identity denied',denied);
 denied:=false; begin perform public.reschedule_cancelled_fixture_safe(h,now()+interval '40 days',now()+interval '40 days 2 hours'); exception when raise_exception then denied:=sqlerrm='Not signed in.'; end;
 insert into lifecycle_results values('reschedule_cancelled_fixture_safe missing identity denied',denied);
 reset role;
 update public.club_memberships set role='admin',is_active=true where club_id=c and member_profile_id=pa;
 perform set_config('request.jwt.claims','{}',true);
 set local role anon;
 denied:=false; begin perform public.cancel_fixture_safe(f,'Rollback test'); exception when raise_exception then denied:=sqlerrm='Not signed in.'; end;
 insert into lifecycle_results values('cancel_fixture_safe anonymous denied',denied);
 denied:=false; begin perform public.fixture_deletion_preview(f); exception when insufficient_privilege then denied:=true; end;
 insert into lifecycle_results values('fixture_deletion_preview anonymous denied',denied);
 denied:=false; begin perform public.delete_fixture(f,'Rollback test'); exception when insufficient_privilege then denied:=true; end;
 insert into lifecycle_results values('delete_fixture with reason anonymous denied',denied);
 denied:=false; begin perform public.delete_fixture(f); exception when insufficient_privilege then denied:=true; end;
 insert into lifecycle_results values('delete_fixture wrapper anonymous denied',denied);
 denied:=false; begin perform public.reschedule_cancelled_fixture_safe(h,now()+interval '40 days',now()+interval '40 days 2 hours'); exception when raise_exception then denied:=sqlerrm='Not signed in.'; end;
 insert into lifecycle_results values('reschedule_cancelled_fixture_safe anonymous denied',denied);
 reset role;
 update public.club_memberships set role='admin',is_active=true where club_id=c and member_profile_id=pa;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 j:=public.fixture_deletion_preview(f);
 insert into lifecycle_results values('admin preview sees player blocker',not (j->>'can_delete')::boolean and (j->>'has_players')::boolean);
 denied:=false; begin perform public.delete_fixture(f,'Rollback test'); exception when raise_exception then denied:=sqlerrm like 'Deletion is blocked because%'; end;
 insert into lifecycle_results values('ordinary delete preserves attached players',denied);
 perform public.cancel_fixture_safe(f,'Rollback cancellation');
 reset role;
 insert into lifecycle_results select 'cancellation records caller and reason',cancelled_at is not null and cancelled_by_member_profile_id=pa and cancellation_reason='Rollback cancellation' from public.fixtures where id=f;
 set local role authenticated;
 replacement:=public.reschedule_cancelled_fixture_safe(f,now()+interval '45 days',now()+interval '45 days 2 hours');
 reset role;
 insert into lifecycle_results select 'replacement belongs to source club',club_id=c and rescheduled_from_fixture_id=f and cancelled_at is null from public.fixtures where id=replacement;
 insert into lifecycle_results select 'source links replacement',rescheduled_to_fixture_id=replacement from public.fixtures where id=f;
 insert into lifecycle_results select 'foreign fixture unchanged',cancelled_at is null and rescheduled_to_fixture_id is null from public.fixtures where id=g;
 set local role authenticated;
 insert into lifecycle_results values('wrapper deletes empty own fixture',public.delete_fixture(h));
 reset role;
 insert into lifecycle_results select 'wrapper deletion effective',not exists(select 1 from public.fixtures where id=h);
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '50 days',false,v,1,4) returning id into h;
 set local role authenticated;
 insert into lifecycle_results values('reason overload deletes empty own fixture',public.delete_fixture(h,'Rollback reason'));
 reset role;
 insert into lifecycle_results select 'reason overload deletion effective',not exists(select 1 from public.fixtures where id=h);
 insert into lifecycle_results values('cron remains disabled',not exists(select 1 from cron.job where active));
 if exists(select 1 from lifecycle_results where not passed) then raise exception 'Lifecycle checks failed'; end if;
end $$;
select * from lifecycle_results order by test;
rollback;
