begin;
set local statement_timeout='25s';
create temp table force_results(test text,passed boolean) on commit drop;
grant insert,select on force_results to authenticated,anon;
do $$
declare
 c uuid:=gen_random_uuid(); d uuid:=gen_random_uuid();
 a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); pa uuid; pb uuid;
 v uuid; w uuid; f uuid; g uuid; h uuid; s uuid; t uuid; u uuid;
 denied boolean; n bigint; baseline bigint;
begin
 if exists(select 1 from cron.job where active) then raise exception 'Disable cron before test'; end if;
 select count(*) into baseline from public.notification_queue;
 insert into public.clubs(id,name) values(c,'ROLLBACK publication own'),(d,'ROLLBACK publication foreign');
 insert into auth.users(id,email,raw_user_meta_data,raw_app_meta_data) values
 (a,a::text||'@example.invalid','{"display_name":"Publication admin"}','{}'),
 (b,b::text||'@example.invalid','{"display_name":"Publication foreign reserve"}','{}');
 select id into pa from public.member_profiles where user_id=a;
 select id into pb from public.member_profiles where user_id=b;
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(c,pa,'admin',true),(d,pb,'member',true);
 insert into public.venues(club_id,name,is_home_venue) values(c,'Rollback own venue',false) returning id into v;
 insert into public.venues(club_id,name,is_home_venue) values(d,'Rollback foreign venue',false) returning id into w;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '30 days',false,v,1,4) returning id into f;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '31 days',false,v,1,4) returning id into h;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(d,now()+interval '32 days',false,w,1,4) returning id into g;
 insert into public.team_selections(fixture_id) values(f) returning id into s;
 insert into public.team_selections(fixture_id) values(g) returning id into t;
 insert into public.team_selections(fixture_id) values(h) returning id into u;
 insert into public.team_selection_members(team_selection_id,member_profile_id,role,is_selected) values(s,pa,'reserve',true),(t,pb,'reserve',true);
 reset role;
 update public.club_memberships set role='admin',is_active=true where club_id=c and member_profile_id=pa;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 denied:=false; begin perform * from public.admin_force_delete_fixture(f,'Rollback test','DELETE FIXTURE'); exception when raise_exception then denied:=sqlerrm='Superuser access required'; end;
 insert into force_results values('admin denied',denied);
 reset role;
 update public.club_memberships set role='member',is_active=true where club_id=c and member_profile_id=pa;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 denied:=false; begin perform * from public.admin_force_delete_fixture(f,'Rollback test','DELETE FIXTURE'); exception when raise_exception then denied:=sqlerrm='Superuser access required'; end;
 insert into force_results values('member denied',denied);
 reset role;
 update public.club_memberships set role='admin',is_active=false where club_id=c and member_profile_id=pa;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 denied:=false; begin perform * from public.admin_force_delete_fixture(f,'Rollback test','DELETE FIXTURE'); exception when raise_exception then denied:=sqlerrm='Superuser access required'; end;
 insert into force_results values('inactive admin denied',denied);
 reset role;
 update public.club_memberships set role='admin',is_active=true where club_id=c and member_profile_id=pa;
 perform set_config('request.jwt.claims','{}',true);
 set local role authenticated;
 denied:=false; begin perform * from public.admin_force_delete_fixture(f,'Rollback test','DELETE FIXTURE'); exception when raise_exception then denied:=sqlerrm='Superuser access required'; end;
 insert into force_results values('missing identity denied',denied);
 reset role;
 update public.club_memberships set role='admin',is_active=true where club_id=c and member_profile_id=pa;
 perform set_config('request.jwt.claims','{}',true);
 set local role anon;
 denied:=false; begin perform * from public.admin_force_delete_fixture(f,'Rollback test','DELETE FIXTURE'); exception when insufficient_privilege then denied:=true; end;
 insert into force_results values('anonymous denied',denied);
 reset role;
 insert into public.app_superusers(user_id) values(a);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 denied:=false; begin perform * from public.admin_force_delete_fixture(f,'Rollback test',null); exception when raise_exception then denied:=sqlerrm='Type DELETE FIXTURE to confirm'; end;
 insert into force_results values('null confirmation rejected',denied);
 denied:=false; begin perform * from public.admin_force_delete_fixture(f,'Rollback test',''); exception when raise_exception then denied:=sqlerrm='Type DELETE FIXTURE to confirm'; end;
 insert into force_results values('empty confirmation rejected',denied);
 denied:=false; begin perform * from public.admin_force_delete_fixture(f,'Rollback test','DELETE'); exception when raise_exception then denied:=sqlerrm='Type DELETE FIXTURE to confirm'; end;
 insert into force_results values('wrong confirmation rejected',denied);
 denied:=false; begin perform * from public.admin_force_delete_fixture(f,'Rollback test','delete fixture'); exception when raise_exception then denied:=sqlerrm='Type DELETE FIXTURE to confirm'; end;
 insert into force_results values('lowercase confirmation rejected',denied);
 reset role;
 insert into force_results select 'rejected requests preserve fixture',exists(select 1 from public.fixtures where id=f);
 set local role authenticated;
 perform * from public.admin_force_delete_fixture(f,'Rollback valid force delete','DELETE FIXTURE');
 reset role;
 insert into force_results select 'superuser explicit confirmation deletes fixture',not exists(select 1 from public.fixtures where id=f);
 insert into force_results select 'force delete clears dependent selections',not exists(select 1 from public.team_selections where fixture_id=f);
 insert into force_results select 'other club fixture preserved',exists(select 1 from public.fixtures where id=g);
 insert into force_results select 'audit retains actor and reason',count(*)=1 from public.audit_journal where fixture_id=f and action='force deletion authorized' and actor_user_id=a and reason='Rollback valid force delete';
 insert into force_results values('cron remains disabled',not exists(select 1 from cron.job where active));
 if exists(select 1 from force_results where not passed) then raise exception 'Force delete checks failed'; end if;
end $$;
select * from force_results order by test;
rollback;
