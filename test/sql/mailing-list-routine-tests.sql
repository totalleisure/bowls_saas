begin;
set local statement_timeout='25s';
create temp table mailing_results(test text,passed boolean) on commit drop;
grant insert,select on mailing_results to authenticated,anon;
do $$
declare
 c uuid:=gen_random_uuid(); d uuid:=gen_random_uuid();
 a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); pa uuid; pb uuid;
 v uuid; w uuid; f uuid; g uuid; h uuid; s uuid; t uuid; u uuid;
 denied boolean; n bigint; baseline bigint; l uuid; m uuid; closed uuid; j jsonb;
begin
 if exists(select 1 from cron.job where active) then raise exception 'Disable cron before test'; end if;
 select count(*) into baseline from public.notification_queue;
 insert into public.clubs(id,name) values(c,'ROLLBACK publication own'),(d,'ROLLBACK publication foreign');
 insert into auth.users(id,email,raw_user_meta_data,raw_app_meta_data) values
 (a,a::text||'@example.invalid','{"display_name":"Publication admin"}','{}'),
 (b,b::text||'@example.invalid','{"display_name":"Publication foreign reserve"}','{}');
 select id into pa from public.member_profiles where user_id=a;
 select id into pb from public.member_profiles where user_id=b;
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(c,pa,'admin',true),(d,pb,'member',true);
 insert into public.venues(club_id,name,is_home_venue) values(c,'Rollback own venue',false) returning id into v;
 insert into public.venues(club_id,name,is_home_venue) values(d,'Rollback foreign venue',false) returning id into w;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '30 days',false,v,1,4) returning id into f;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '31 days',false,v,1,4) returning id into h;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(d,now()+interval '32 days',false,w,1,4) returning id into g;
 insert into public.team_selections(fixture_id) values(f) returning id into s;
 insert into public.team_selections(fixture_id) values(g) returning id into t;
 insert into public.team_selections(fixture_id) values(h) returning id into u;
 insert into public.team_selection_members(team_selection_id,member_profile_id,role,is_selected) values(s,pa,'reserve',true),(t,pb,'reserve',true);
 update public.member_profiles set email_address=a::text||'@example.invalid' where id=pa;
 insert into public.mailing_lists(club_id,name,allow_self_subscription) values(c,'Rollback own list',true) returning id into l;
 insert into public.mailing_lists(club_id,name,allow_self_subscription) values(d,'Rollback foreign list',true) returning id into m;
 insert into public.mailing_lists(club_id,name,allow_self_subscription) values(c,'Rollback managed list',false) returning id into closed;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 insert into mailing_results select 'only own self subscription list visible',count(*)=1 and bool_and(mailing_list_id=l) from public.my_self_subscribable_mailing_lists(c);
 j:=public.set_my_mailing_list_membership(l,true);
 insert into mailing_results values('own join identifies caller',j->>'member_profile_id'=pa::text and (j->>'is_joined')::boolean);
 insert into mailing_results select 'own join reflected in list',bool_and(is_joined) from public.my_self_subscribable_mailing_lists(c);
 j:=public.set_my_mailing_list_membership(l,false);
 insert into mailing_results select 'own leave reflected in list',bool_and(not is_joined) from public.my_self_subscribable_mailing_lists(c);
 perform public.set_my_mailing_list_membership(l,true);
 denied:=false; begin perform * from public.my_self_subscribable_mailing_lists(d); exception when raise_exception then denied:=sqlerrm='You are not an active member of this club.'; end;
 insert into mailing_results values('foreign lists denied',denied);
 denied:=false; begin perform * from public.set_my_mailing_list_membership(m,true); exception when raise_exception then denied:=sqlerrm='You are not eligible to join mailing or volunteer lists.'; end;
 insert into mailing_results values('foreign join denied',denied);
 denied:=false; begin perform * from public.set_my_mailing_list_membership(closed,true); exception when raise_exception then denied:=sqlerrm='This mailing list is managed by the club administrator.'; end;
 insert into mailing_results values('admin managed list self join denied',denied);
 denied:=false; begin perform * from public.queue_mailing_list_message(m,'Test','Test',true,false); exception when raise_exception then denied:=sqlerrm='You do not have permission to send to this mailing list.'; end;
 insert into mailing_results values('foreign send denied',denied);
 j:=public.queue_mailing_list_message(l,'Test','Test',true,true);
 insert into mailing_results values('own admin queues own subscribed recipient',(j->>'recipient_count')::integer=1 and (j->>'app_messages_created')::integer=1 and (j->>'emails_queued')::integer=1);
 reset role;
 insert into mailing_results select 'message records actual sender and club',count(*)=1 and bool_and(sender_member_profile_id=pa and club_id=c) from public.mailing_list_messages where mailing_list_id=l;
 insert into mailing_results select 'no foreign recipient queued',count(*)=0 from public.email_queue where member_profile_id=pb and payload->>'mailing_list_id'=l::text;
 update public.club_memberships set role='member',is_active=true where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false; begin perform * from public.queue_mailing_list_message(l,'Test','Test',true,false); exception when raise_exception then denied:=sqlerrm='You do not have permission to send to this mailing list.'; end;
 insert into mailing_results values('member cannot send',denied);
 reset role;
 update public.club_memberships set role='guest',is_active=true where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false; begin perform * from public.queue_mailing_list_message(l,'Test','Test',true,false); exception when raise_exception then denied:=sqlerrm='You do not have permission to send to this mailing list.'; end;
 insert into mailing_results values('guest cannot send',denied);
 denied:=false; begin perform * from public.set_my_mailing_list_membership(l,true); exception when raise_exception then denied:=sqlerrm='You are not eligible to join mailing or volunteer lists.'; end;
 insert into mailing_results values('guest cannot subscribe',denied);
 reset role;
 update public.club_memberships set role='admin',is_active=false where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false; begin perform * from public.queue_mailing_list_message(l,'Test','Test',true,false); exception when raise_exception then denied:=sqlerrm='You do not have permission to send to this mailing list.'; end;
 insert into mailing_results values('inactive admin cannot send',denied);
 denied:=false; begin perform * from public.set_my_mailing_list_membership(l,true); exception when raise_exception then denied:=sqlerrm='You are not eligible to join mailing or volunteer lists.'; end;
 insert into mailing_results values('inactive admin cannot subscribe',denied);
 denied:=false; begin perform * from public.my_self_subscribable_mailing_lists(c); exception when raise_exception then denied:=sqlerrm='You are not an active member of this club.'; end;
 insert into mailing_results values('inactive list read denied',denied);
 reset role;
 insert into public.app_superusers(user_id) values(a);
 set local role authenticated;
 j:=public.queue_mailing_list_message(m,'Test','Test',true,false);
 insert into mailing_results values('superuser may send foreign list',(j->>'recipient_count')::integer=0);
 reset role;
 perform set_config('request.jwt.claims','{}',true);
 set local role authenticated;
 denied:=false; begin perform * from public.my_self_subscribable_mailing_lists(c); exception when raise_exception then denied:=sqlerrm='You must be signed in.'; end;
 insert into mailing_results values('authenticated without identity read denied',denied);
 denied:=false; begin perform * from public.set_my_mailing_list_membership(l,true); exception when raise_exception then denied:=sqlerrm='You must be signed in.'; end;
 insert into mailing_results values('authenticated without identity join denied',denied);
 denied:=false; begin perform * from public.queue_mailing_list_message(l,'Test','Test',true,false); exception when raise_exception then denied:=sqlerrm='You must be signed in.'; end;
 insert into mailing_results values('authenticated without identity send denied',denied);
 reset role;
 set local role anon;
 denied:=false; begin perform * from public.my_self_subscribable_mailing_lists(c); exception when raise_exception then denied:=sqlerrm='You must be signed in.'; end;
 insert into mailing_results values('anon without identity read denied',denied);
 denied:=false; begin perform * from public.set_my_mailing_list_membership(l,true); exception when raise_exception then denied:=sqlerrm='You must be signed in.'; end;
 insert into mailing_results values('anon without identity join denied',denied);
 denied:=false; begin perform * from public.queue_mailing_list_message(l,'Test','Test',true,false); exception when raise_exception then denied:=sqlerrm='You must be signed in.'; end;
 insert into mailing_results values('anon without identity send denied',denied);
 reset role;
 insert into mailing_results values('cron remains disabled',not exists(select 1 from cron.job where active));
 if exists(select 1 from mailing_results where not passed) then raise exception 'Mailing checks failed'; end if;
end $$;
select * from mailing_results order by test;
rollback;
