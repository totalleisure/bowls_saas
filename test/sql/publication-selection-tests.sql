begin;
set local statement_timeout='25s';
create temp table publication_results(test text,passed boolean) on commit drop;
grant insert,select on publication_results to authenticated,anon;
do $$
declare
 c uuid:=gen_random_uuid(); d uuid:=gen_random_uuid();
 a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); pa uuid; pb uuid;
 v uuid; w uuid; f uuid; g uuid; h uuid; s uuid; t uuid; u uuid;
 denied boolean; n bigint; baseline bigint;
begin
 if exists(select 1 from cron.job where active) then raise exception 'Disable cron before test'; end if;
 select count(*) into baseline from public.notification_queue;
 insert into public.clubs(id,name) values(c,'ROLLBACK publication own'),(d,'ROLLBACK publication foreign');
 insert into auth.users(id,email,raw_user_meta_data,raw_app_meta_data) values
 (a,a::text||'@example.invalid','{"display_name":"Publication admin"}','{}'),
 (b,b::text||'@example.invalid','{"display_name":"Publication foreign reserve"}','{}');
 select id into pa from public.member_profiles where user_id=a;
 select id into pb from public.member_profiles where user_id=b;
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(c,pa,'admin',true),(d,pb,'member',true);
 insert into public.venues(club_id,name,is_home_venue) values(c,'Rollback own venue',false) returning id into v;
 insert into public.venues(club_id,name,is_home_venue) values(d,'Rollback foreign venue',false) returning id into w;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '30 days',false,v,1,4) returning id into f;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '31 days',false,v,1,4) returning id into h;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(d,now()+interval '32 days',false,w,1,4) returning id into g;
 insert into public.team_selections(fixture_id) values(f) returning id into s;
 insert into public.team_selections(fixture_id) values(g) returning id into t;
 insert into public.team_selections(fixture_id) values(h) returning id into u;
 insert into public.team_selection_members(team_selection_id,member_profile_id,role,is_selected) values(s,pa,'reserve',true),(t,pb,'reserve',true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 denied:=false;
 begin perform public.queue_team_publication_communications(f,t); exception when sqlstate '22023' then denied:=true; end;
 insert into publication_results values('cross club selection rejected',denied);
 denied:=false;
 begin perform public.queue_team_publication_communications(f,u); exception when sqlstate '22023' then denied:=true; end;
 insert into publication_results values('same club wrong fixture rejected',denied);
 denied:=false;
 begin perform public.queue_team_publication_communications(f,null); exception when sqlstate '22023' then denied:=true; end;
 insert into publication_results values('null selection rejected',denied);
 denied:=false;
 begin perform public.queue_team_publication_communications(f,gen_random_uuid()); exception when sqlstate '22023' then denied:=true; end;
 insert into publication_results values('unknown selection rejected',denied);
 denied:=false;
 begin perform public.queue_team_publication_communications(g,t); exception when raise_exception then denied:=sqlerrm='You do not have permission to queue team communications.'; end;
 insert into publication_results values('foreign fixture permission denied',denied);
 reset role;
 insert into publication_results select 'rejected requests leave queue unchanged',count(*)=baseline from public.notification_queue;
 set local role authenticated;
 perform public.queue_team_publication_communications(f,s);
 reset role;
 insert into publication_results select 'valid own reserve queued',count(*)=1 from public.notification_queue where fixture_id=f and team_selection_id=s and target_member_profile_id=pa and event_type='team_published_reserve';
 insert into publication_results select 'foreign reserve never queued',count(*)=0 from public.notification_queue where target_member_profile_id=pb;
 set local role authenticated;
 perform public.queue_team_publication_communications(f,s);
 reset role;
 insert into publication_results select 'repeat request does not duplicate reserve',count(*)=1 from public.notification_queue where fixture_id=f and team_selection_id=s;
 update public.club_memberships set is_active=false where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false;
 begin perform public.queue_team_publication_communications(f,s); exception when raise_exception then denied:=sqlerrm='You do not have permission to queue team communications.'; end;
 insert into publication_results values('inactive admin rejected',denied);
 reset role;
 perform set_config('request.jwt.claims','{}',true);
 set local role authenticated;
 denied:=false;
 begin perform public.queue_team_publication_communications(f,s); exception when raise_exception then denied:=sqlerrm='Not signed in.'; end;
 insert into publication_results values('missing identity rejected',denied);
 reset role;
 set local role anon;
 denied:=false;
 begin perform public.queue_team_publication_communications(f,s); exception when insufficient_privilege then denied:=true; end;
 insert into publication_results values('anonymous execute denied',denied);
 reset role;
 insert into publication_results values('cron remains disabled',not exists(select 1 from cron.job where active));
 if exists(select 1 from publication_results where not passed) then raise exception 'Publication tests failed'; end if;
end $$;
select * from publication_results order by test;
rollback;

