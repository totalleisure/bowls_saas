begin;
set local statement_timeout='25s';
create temp table actor_results(test text,passed boolean) on commit drop;
grant insert,select on actor_results to authenticated,anon;
do $$
declare
 c uuid:=gen_random_uuid(); d uuid:=gen_random_uuid();
 a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); pa uuid; pb uuid;
 v uuid; w uuid; f uuid; g uuid; h uuid; s uuid; t uuid; u uuid;
 denied boolean; n bigint; baseline bigint;
begin
 if exists(select 1 from cron.job where active) then raise exception 'Disable cron before test'; end if;
 select count(*) into baseline from public.notification_queue;
 insert into public.clubs(id,name) values(c,'ROLLBACK publication own'),(d,'ROLLBACK publication foreign');
 insert into auth.users(id,email,raw_user_meta_data,raw_app_meta_data) values
 (a,a::text||'@example.invalid','{"display_name":"Publication admin"}','{}'),
 (b,b::text||'@example.invalid','{"display_name":"Publication foreign reserve"}','{}');
 select id into pa from public.member_profiles where user_id=a;
 select id into pb from public.member_profiles where user_id=b;
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(c,pa,'admin',true),(d,pb,'member',true);
 insert into public.venues(club_id,name,is_home_venue) values(c,'Rollback own venue',false) returning id into v;
 insert into public.venues(club_id,name,is_home_venue) values(d,'Rollback foreign venue',false) returning id into w;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '30 days',false,v,1,4) returning id into f;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '31 days',false,v,1,4) returning id into h;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(d,now()+interval '32 days',false,w,1,4) returning id into g;
 insert into public.team_selections(fixture_id) values(f) returning id into s;
 insert into public.team_selections(fixture_id) values(g) returning id into t;
 insert into public.team_selections(fixture_id) values(h) returning id into u;
 insert into public.team_selection_members(team_selection_id,member_profile_id,role,is_selected) values(s,pa,'reserve',true),(t,pb,'reserve',true);

 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 perform public.process_fixture_post_publish_changes(f,'fixture_details_changed');
 perform public.process_fixture_post_publish_changes(f,'fixture_details_changed',pa);
 perform public.process_fixture_post_publish_communications(f,pa);
 denied:=false;
 begin perform public.process_fixture_post_publish_changes(f,'fixture_details_changed',pb); exception when sqlstate '22023' then denied:=true; end;
 insert into actor_results values('direct actor spoof denied',denied);
 denied:=false;
 begin perform public.process_fixture_post_publish_communications(f,pb); exception when sqlstate '22023' then denied:=true; end;
 insert into actor_results values('wrapper actor spoof denied',denied);
 denied:=false;
 begin perform public.process_fixture_post_publish_changes(g,'fixture_details_changed',pa); exception when raise_exception then denied:=sqlerrm='You do not have permission to process post-publish communications for this fixture.'; end;
 insert into actor_results values('foreign fixture denied',denied);
 reset role;
 insert into actor_results select 'valid omitted and explicit actor recorded',count(*)=3 and bool_and(changed_by_member_profile_id=pa) from public.fixture_communication_audit where fixture_id=f;
 update public.club_memberships set is_active=false where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false;
 begin perform public.process_fixture_post_publish_changes(f,'fixture_details_changed'); exception when raise_exception then denied:=sqlerrm='You do not have permission to process post-publish communications for this fixture.'; end;
 insert into actor_results values('inactive admin denied',denied);
 reset role;
 insert into public.app_superusers(user_id) values(a);
 set local role authenticated;
 perform public.process_fixture_post_publish_changes(g,'fixture_details_changed');
 denied:=false;
 begin perform public.process_fixture_post_publish_changes(g,'fixture_details_changed',pb); exception when sqlstate '22023' then denied:=true; end;
 insert into actor_results values('superuser actor spoof denied',denied);
 reset role;
 insert into actor_results select 'superuser cross club uses own identity',count(*)=1 and bool_and(changed_by_member_profile_id=pa) from public.fixture_communication_audit where fixture_id=g;
 perform set_config('request.jwt.claims','{}',true);
 set local role authenticated;
 denied:=false;
 begin perform public.process_fixture_post_publish_changes(f,'fixture_details_changed',pa); exception when raise_exception then denied:=sqlerrm='A signed-in member profile is required.'; end;
 insert into actor_results values('missing identity with supplied actor denied',denied);
 reset role;
 set local role anon;
 denied:=false;
 begin perform public.process_fixture_post_publish_communications(f,pa); exception when raise_exception then denied:=sqlerrm='A signed-in member profile is required.'; end;
 insert into actor_results values('anonymous wrapper denied',denied);
 reset role;
 perform set_config('request.jwt.claims','{"role":"service_role"}',true);
 set local role service_role;
 perform public.process_fixture_post_publish_changes(g,'fixture_details_changed',pb);
 reset role;
 insert into actor_results select 'server explicit actor retained',count(*)=1 from public.fixture_communication_audit where fixture_id=g and changed_by_member_profile_id=pb;
 insert into actor_results select 'no notification side effects',count(*)=baseline from public.notification_queue;
 insert into actor_results values('cron remains disabled',not exists(select 1 from cron.job where active));
 if exists(select 1 from actor_results where not passed) then raise exception 'Actor tests failed'; end if;
end $$;
select * from actor_results order by test;
rollback;
