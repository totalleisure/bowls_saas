begin;
set local statement_timeout='25s';
create temp table selection_results(test text,passed boolean) on commit drop;
grant insert,select on selection_results to authenticated,anon;
do $$
declare
 c uuid:=gen_random_uuid(); d uuid:=gen_random_uuid();
 a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); pa uuid; pb uuid;
 v uuid; w uuid; f uuid; g uuid; h uuid; s uuid; t uuid; u uuid;
 denied boolean; n bigint; baseline bigint; r uuid; z uuid; j jsonb;
begin
 if exists(select 1 from cron.job where active) then raise exception 'Disable cron before test'; end if;
 select count(*) into baseline from public.notification_queue;
 insert into public.clubs(id,name) values(c,'ROLLBACK publication own'),(d,'ROLLBACK publication foreign');
 insert into auth.users(id,email,raw_user_meta_data,raw_app_meta_data) values
 (a,a::text||'@example.invalid','{"display_name":"Publication admin"}','{}'),
 (b,b::text||'@example.invalid','{"display_name":"Publication foreign reserve"}','{}');
 select id into pa from public.member_profiles where user_id=a;
 select id into pb from public.member_profiles where user_id=b;
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(c,pa,'admin',true),(d,pb,'member',true);
 insert into public.venues(club_id,name,is_home_venue) values(c,'Rollback own venue',false) returning id into v;
 insert into public.venues(club_id,name,is_home_venue) values(d,'Rollback foreign venue',false) returning id into w;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '30 days',false,v,1,4) returning id into f;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '31 days',false,v,1,4) returning id into h;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(d,now()+interval '32 days',false,w,1,4) returning id into g;
 insert into public.team_selections(fixture_id) values(f) returning id into s;
 insert into public.team_selections(fixture_id) values(g) returning id into t;
 insert into public.team_selections(fixture_id) values(h) returning id into u;
 insert into public.team_selection_members(team_selection_id,member_profile_id,role,is_selected) values(s,pa,'reserve',true),(t,pb,'reserve',true);

 insert into public.fixture_rinks(fixture_id,fixture_rink_no,format,players_per_rink) values(f,1,'rinks',4) returning id into r;
 insert into public.fixture_rinks(fixture_id,fixture_rink_no,format,players_per_rink) values(g,1,'rinks',4) returning id into z;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 j:=public.set_team_selection_member_role(s,pa,'player');
 insert into selection_results values('admin can promote reserve',j->>'action'='reserve_promoted');
 perform public.save_fixture_rink_assignments(f,s,jsonb_build_array(jsonb_build_object('fixture_rink_id',r,'member_profile_id',pa,'position',1)));
 reset role;
 insert into selection_results select 'admin assignment saved',count(*)=1 from public.fixture_rink_assignments where fixture_id=f and member_profile_id=pa and position=1;
 set local role authenticated;
 j:=public.set_team_selection_member_role(s,pa,'reserve');
 insert into selection_results values('admin can demote player',j->>'action'='player_demoted');
 reset role;
 insert into selection_results select 'demotion clears assignment',count(*)=0 from public.fixture_rink_assignments where fixture_id=f;
 set local role authenticated;
 j:=public.set_team_selection_member_active(s,pa,false);
 insert into selection_results values('admin can deselect member',j->>'action'='removed');
 j:=public.set_team_selection_member_active(s,pa,true);
 insert into selection_results values('admin can reselect member',j->>'action'='selected');
 denied:=false;
 begin perform public.set_team_selection_member_active(t,pb,false); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('foreign selection active change denied',denied);
 denied:=false;
 begin perform public.set_team_selection_member_role(t,pb,'player'); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('foreign selection role change denied',denied);
 denied:=false;
 begin perform public.save_fixture_rink_assignments(g,t,'[]'); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('foreign fixture assignment denied',denied);
 denied:=false;
 begin perform public.save_fixture_rink_assignments(f,t,'[]'); exception when raise_exception then denied:=sqlerrm='Team selection does not belong to this fixture.'; end;
 insert into selection_results values('wrong selection fixture pair denied',denied);
 denied:=false;
 begin perform public.save_fixture_rink_assignments(f,s,jsonb_build_array(jsonb_build_object('fixture_rink_id',z,'member_profile_id',pa,'position',1))); exception when raise_exception then denied:=sqlerrm='Invalid team/rink assignment.'; end;
 insert into selection_results values('foreign rink rejected',denied);
 denied:=false;
 begin perform public.set_team_selection_member_active(s,pb,true); exception when raise_exception then denied:=sqlerrm='Target member is not an active non-Guest member of this club'; end;
 insert into selection_results values('foreign member cannot be selected',denied);
 reset role;
 insert into public.team_selection_members(team_selection_id,member_profile_id,role,is_selected) values(s,pb,'reserve',true);
 set local role authenticated;
 denied:=false;
 begin perform public.set_team_selection_member_role(s,pb,'player'); exception when raise_exception then denied:=sqlerrm='Target member is not an active non-Guest member of this club'; end;
 insert into selection_results values('foreign stale selected member role denied',denied);
 denied:=false;
 begin perform public.save_fixture_rink_assignments(f,s,jsonb_build_array(jsonb_build_object('fixture_rink_id',r,'member_profile_id',pb,'position',1))); exception when raise_exception then denied:=sqlerrm='Target member is not an active non-Guest member of this club'; end;
 insert into selection_results values('foreign stale selected member assignment denied',denied);
 reset role;
 update public.club_memberships set role='member',is_active=true where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false;
 begin perform public.set_team_selection_member_active(s,pa,true); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('ordinary member cannot select',denied);
 denied:=false;
 begin perform public.set_team_selection_member_role(s,pa,'reserve'); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('ordinary member cannot change role',denied);
 denied:=false;
 begin perform public.save_fixture_rink_assignments(f,s,'[]'); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('ordinary member cannot assign',denied);
 reset role;
 update public.club_memberships set role='guest',is_active=true where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false;
 begin perform public.set_team_selection_member_active(s,pa,true); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('guest cannot select',denied);
 denied:=false;
 begin perform public.set_team_selection_member_role(s,pa,'reserve'); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('guest cannot change role',denied);
 denied:=false;
 begin perform public.save_fixture_rink_assignments(f,s,'[]'); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('guest cannot assign',denied);
 reset role;
 update public.club_memberships set role='admin',is_active=false where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false;
 begin perform public.set_team_selection_member_active(s,pa,true); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('inactive admin cannot select',denied);
 denied:=false;
 begin perform public.set_team_selection_member_role(s,pa,'reserve'); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('inactive admin cannot change role',denied);
 denied:=false;
 begin perform public.save_fixture_rink_assignments(f,s,'[]'); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('inactive admin cannot assign',denied);
 reset role;
 update public.club_memberships set role='member',is_active=true where club_id=c and member_profile_id=pa;
 update public.fixtures set captain_member_profile_id=pa where id=f;
 set local role authenticated;
 perform public.set_team_selection_member_active(s,pa,true);
 perform public.set_team_selection_member_role(s,pa,'reserve');
 perform public.save_fixture_rink_assignments(f,s,'[]');
 insert into selection_results values('active fixture captain can use all three routines',true);
 reset role;
 update public.club_memberships set is_active=false where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false;
 begin perform public.set_team_selection_member_active(s,pa,true); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('inactive fixture captain cannot select',denied);
 denied:=false;
 begin perform public.set_team_selection_member_role(s,pa,'player'); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('inactive fixture captain cannot change role',denied);
 denied:=false;
 begin perform public.save_fixture_rink_assignments(f,s,'[]'); exception when raise_exception then denied:=sqlerrm='You do not have permission to manage this fixture.'; end;
 insert into selection_results values('inactive fixture captain cannot assign',denied);
 reset role;
 insert into public.app_superusers(user_id) values(a);
 set local role authenticated;
 perform public.set_team_selection_member_active(t,pb,true);
 perform public.set_team_selection_member_role(t,pb,'player');
 perform public.save_fixture_rink_assignments(g,t,jsonb_build_array(jsonb_build_object('fixture_rink_id',z,'member_profile_id',pb,'position',1)));
 insert into selection_results values('superuser can manage foreign club with eligible player',true);
 reset role;
 perform set_config('request.jwt.claims','{}',true);
 set local role authenticated;
 denied:=false;
 begin perform public.set_team_selection_member_active(s,pa,true); exception when raise_exception then denied:=sqlerrm='Not signed in.'; end;
 insert into selection_results values('missing identity select denied',denied);
 reset role;
 set local role anon;
 denied:=false;
 begin perform public.set_team_selection_member_active(s,pa,true); exception when insufficient_privilege then denied:=true; end;
 insert into selection_results values('anonymous select denied',denied);
 reset role;
 set local role authenticated;
 denied:=false;
 begin perform public.set_team_selection_member_role(s,pa,'player'); exception when raise_exception then denied:=sqlerrm='Not signed in.'; end;
 insert into selection_results values('missing identity role denied',denied);
 reset role;
 set local role anon;
 denied:=false;
 begin perform public.set_team_selection_member_role(s,pa,'player'); exception when insufficient_privilege then denied:=true; end;
 insert into selection_results values('anonymous role denied',denied);
 reset role;
 set local role authenticated;
 denied:=false;
 begin perform public.save_fixture_rink_assignments(f,s,'[]'); exception when raise_exception then denied:=sqlerrm='Not signed in.'; end;
 insert into selection_results values('missing identity assign denied',denied);
 reset role;
 set local role anon;
 denied:=false;
 begin perform public.save_fixture_rink_assignments(f,s,'[]'); exception when insufficient_privilege then denied:=true; end;
 insert into selection_results values('anonymous assign denied',denied);
 reset role;
 set local role authenticated;
 reset role;
 insert into selection_results values('cron remains disabled',not exists(select 1 from cron.job where active));
 if exists(select 1 from selection_results where not passed) then raise exception 'Selection authorization tests failed'; end if;
end $$;
select * from selection_results order by test;
rollback;
