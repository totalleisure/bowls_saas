begin;
set local statement_timeout='25s';
create temp table attachment_results(test text,passed boolean) on commit drop;
grant insert,select on attachment_results to authenticated,anon;
do $$
declare
 c uuid:=gen_random_uuid(); d uuid:=gen_random_uuid();
 a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); pa uuid; pb uuid;
 v uuid; w uuid; f uuid; g uuid; h uuid; s uuid; t uuid; u uuid;
 denied boolean; n bigint; baseline bigint; doc jsonb; result jsonb;
begin
 if exists(select 1 from cron.job where active) then raise exception 'Disable cron before test'; end if;
 select count(*) into baseline from public.notification_queue;
 insert into public.clubs(id,name) values(c,'ROLLBACK publication own'),(d,'ROLLBACK publication foreign');
 insert into auth.users(id,email,raw_user_meta_data,raw_app_meta_data) values
 (a,a::text||'@example.invalid','{"display_name":"Publication admin"}','{}'),
 (b,b::text||'@example.invalid','{"display_name":"Publication foreign reserve"}','{}');
 select id into pa from public.member_profiles where user_id=a;
 select id into pb from public.member_profiles where user_id=b;
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(c,pa,'admin',true),(d,pb,'member',true);
 insert into public.venues(club_id,name,is_home_venue) values(c,'Rollback own venue',false) returning id into v;
 insert into public.venues(club_id,name,is_home_venue) values(d,'Rollback foreign venue',false) returning id into w;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '30 days',false,v,1,4) returning id into f;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '31 days',false,v,1,4) returning id into h;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(d,now()+interval '32 days',false,w,1,4) returning id into g;
 insert into public.team_selections(fixture_id) values(f) returning id into s;
 insert into public.team_selections(fixture_id) values(g) returning id into t;
 insert into public.team_selections(fixture_id) values(h) returning id into u;
 insert into public.team_selection_members(team_selection_id,member_profile_id,role,is_selected) values(s,pa,'reserve',true),(t,pb,'reserve',true);
 update public.team_selections set status='published' where id=s;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 doc:=jsonb_build_object('name','test.pdf','contentType','application/pdf','contentBytes',encode(convert_to('%PDF-1.4 test','UTF8'),'base64'),'compositionVersion',0);
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,doc-'contentType'); exception when raise_exception then denied:=sqlerrm like 'Invalid or obsolete team-sheet attachment%'; end;
 insert into attachment_results values('missing content type rejected',denied);
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,doc||jsonb_build_object('contentType',null)); exception when raise_exception then denied:=sqlerrm like 'Invalid or obsolete team-sheet attachment%'; end;
 insert into attachment_results values('null content type rejected',denied);
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,doc||'{"contentType":"text/plain"}'::jsonb); exception when raise_exception then denied:=sqlerrm like 'Invalid or obsolete team-sheet attachment%'; end;
 insert into attachment_results values('wrong content type rejected',denied);
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,doc-'compositionVersion'); exception when raise_exception then denied:=sqlerrm like 'Invalid or obsolete team-sheet attachment%'; end;
 insert into attachment_results values('missing version rejected',denied);
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,doc||jsonb_build_object('compositionVersion',null)); exception when raise_exception then denied:=sqlerrm like 'Invalid or obsolete team-sheet attachment%'; end;
 insert into attachment_results values('null version rejected',denied);
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,doc||'{"compositionVersion":1}'::jsonb); exception when raise_exception then denied:=sqlerrm like 'Invalid or obsolete team-sheet attachment%'; end;
 insert into attachment_results values('stale version rejected',denied);
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,doc-'name'); exception when raise_exception then denied:=sqlerrm like 'Invalid or obsolete team-sheet attachment%'; end;
 insert into attachment_results values('missing name rejected',denied);
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,doc||'{"contentBytes":""}'::jsonb); exception when raise_exception then denied:=sqlerrm like 'Invalid or obsolete team-sheet attachment%'; end;
 insert into attachment_results values('empty content rejected',denied);
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,null); exception when raise_exception then denied:=sqlerrm like 'Invalid or obsolete team-sheet attachment%'; end;
 insert into attachment_results values('null attachment rejected',denied);
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,'[]'::jsonb); exception when raise_exception then denied:=sqlerrm like 'Invalid or obsolete team-sheet attachment%'; end;
 insert into attachment_results values('array attachment rejected',denied);
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,1,doc); exception when raise_exception then denied:=sqlerrm like 'Team composition changed.%'; end;
 insert into attachment_results values('wrong expected version rejected',denied);
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,t,0,doc); exception when raise_exception then denied:=sqlerrm='Published team selection not found for this fixture.'; end;
 insert into attachment_results values('wrong selection rejected',denied);
 denied:=false;
 begin perform public.attach_publication_team_sheet(g,t,0,doc); exception when raise_exception then denied:=sqlerrm='You do not have permission to attach this team sheet.'; end;
 insert into attachment_results values('foreign fixture rejected',denied);
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,doc||jsonb_build_object('contentBytes',encode(convert_to('plain text','UTF8'),'base64'))); exception when raise_exception then denied:=sqlerrm='The Team Sheet attachment is not a valid PDF.'; end;
 insert into attachment_results values('non PDF bytes rejected',denied);
 perform public.queue_team_publication_communications(f,s);
 result:=public.attach_publication_team_sheet(f,s,0,doc);
 insert into attachment_results values('valid attachment updates queue',(result->>'notification_rows_updated')::integer=1);
 reset role;
 insert into attachment_results select 'stored attachment matches requested document',count(*)=1 and bool_and(payload->'attachments'=jsonb_build_array(doc)) from public.notification_queue where fixture_id=f and team_selection_id=s;
 set local role authenticated;
 result:=public.attach_publication_team_sheet(f,s,0,doc);
 insert into attachment_results values('repeat attachment does not rewrite queue',(result->>'notification_rows_updated')::integer=0);
 reset role;
 update public.club_memberships set role='member' where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,doc); exception when raise_exception then denied:=sqlerrm='You do not have permission to attach this team sheet.'; end;
 insert into attachment_results values('ordinary selected member rejected',denied);
 reset role;
 update public.club_memberships set role='admin',is_active=false where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,doc); exception when raise_exception then denied:=sqlerrm='You do not have permission to attach this team sheet.'; end;
 insert into attachment_results values('inactive admin rejected',denied);
 reset role;
 insert into public.app_superusers(user_id) values(a);
 set local role authenticated;
 result:=public.attach_publication_team_sheet(f,s,0,doc);
 insert into attachment_results values('superuser allowed',result->>'composition_version'='0');
 reset role;
 perform set_config('request.jwt.claims','{}',true);
 set local role authenticated;
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,doc); exception when raise_exception then denied:=sqlerrm='Not signed in.'; end;
 insert into attachment_results values('missing identity rejected',denied);
 reset role;
 set local role anon;
 denied:=false;
 begin perform public.attach_publication_team_sheet(f,s,0,doc); exception when insufficient_privilege then denied:=true; end;
 insert into attachment_results values('anonymous execute denied',denied);
 reset role;
 insert into attachment_results values('cron remains disabled',not exists(select 1 from cron.job where active));
 if exists(select 1 from attachment_results where not passed) then raise exception 'Attachment checks failed'; end if;
end $$;
select * from attachment_results order by test;
rollback;
