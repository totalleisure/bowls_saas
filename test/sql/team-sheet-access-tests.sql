begin;
set local statement_timeout='25s';
create temp table sheet_results(test text,passed boolean) on commit drop;
grant insert,select on sheet_results to authenticated,anon;
do $$
declare
 c uuid:=gen_random_uuid(); d uuid:=gen_random_uuid();
 a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); pa uuid; pb uuid;
 v uuid; w uuid; f uuid; g uuid; h uuid; s uuid; t uuid; u uuid;
 denied boolean; n bigint; baseline bigint; j jsonb; r uuid;
begin
 if exists(select 1 from cron.job where active) then raise exception 'Disable cron before test'; end if;
 select count(*) into baseline from public.notification_queue;
 insert into public.clubs(id,name) values(c,'ROLLBACK publication own'),(d,'ROLLBACK publication foreign');
 insert into auth.users(id,email,raw_user_meta_data,raw_app_meta_data) values
 (a,a::text||'@example.invalid','{"display_name":"Publication admin"}','{}'),
 (b,b::text||'@example.invalid','{"display_name":"Publication foreign reserve"}','{}');
 select id into pa from public.member_profiles where user_id=a;
 select id into pb from public.member_profiles where user_id=b;
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(c,pa,'admin',true),(d,pb,'member',true);
 insert into public.venues(club_id,name,is_home_venue) values(c,'Rollback own venue',false) returning id into v;
 insert into public.venues(club_id,name,is_home_venue) values(d,'Rollback foreign venue',false) returning id into w;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '30 days',false,v,1,4) returning id into f;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '31 days',false,v,1,4) returning id into h;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(d,now()+interval '32 days',false,w,1,4) returning id into g;
 insert into public.team_selections(fixture_id) values(f) returning id into s;
 insert into public.team_selections(fixture_id) values(g) returning id into t;
 insert into public.team_selections(fixture_id) values(h) returning id into u;
 insert into public.team_selection_members(team_selection_id,member_profile_id,role,is_selected) values(s,pa,'reserve',true),(t,pb,'reserve',true);

 update public.team_selections set status='published' where id=s;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 j:=public.get_authorized_team_sheet_data(f);
 insert into sheet_results values('active admin allowed',j#>>'{access,can_manage}'='true');
 reset role;
 update public.club_memberships set role='member' where club_id=c and member_profile_id=pa;
 set local role authenticated;
 j:=public.get_authorized_team_sheet_data(f);
 insert into sheet_results values('active selected reserve allowed',j#>>'{fixture,id}'=f::text and j#>>'{access,can_manage}'='false');
 reset role;
 update public.club_memberships set is_active=false where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false;
 begin perform public.get_authorized_team_sheet_data(f); exception when raise_exception then denied:=sqlerrm='Not authorised to view this team sheet.'; end;
 insert into sheet_results values('inactive selected reserve denied',denied);
 reset role;
 update public.club_memberships set is_active=true where club_id=c and member_profile_id=pa;
 update public.team_selection_members set is_selected=false where team_selection_id=s and member_profile_id=pa;
 set local role authenticated;
 denied:=false;
 begin perform public.get_authorized_team_sheet_data(f); exception when raise_exception then denied:=sqlerrm='Not authorised to view this team sheet.'; end;
 insert into sheet_results values('unselected active member denied',denied);
 reset role;
 update public.team_selection_members set is_selected=true,role='player' where team_selection_id=s and member_profile_id=pa;
 set local role authenticated;
 denied:=false;
 begin perform public.get_authorized_team_sheet_data(f); exception when raise_exception then denied:=sqlerrm='Not authorised to view this team sheet.'; end;
 insert into sheet_results values('unpositioned player denied',denied);
 reset role;
 insert into public.fixture_rinks(fixture_id,fixture_rink_no,format,players_per_rink) values(f,1,'rinks',4) returning id into r;
 insert into public.fixture_rink_assignments(fixture_id,fixture_rink_id,position,member_profile_id) values(f,r,1,pa);
 set local role authenticated;
 j:=public.get_authorized_team_sheet_data(f);
 insert into sheet_results values('active positioned player allowed',j#>>'{fixture,id}'=f::text);
 reset role;
 update public.club_memberships set is_active=false where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false;
 begin perform public.get_authorized_team_sheet_data(f); exception when raise_exception then denied:=sqlerrm='Not authorised to view this team sheet.'; end;
 insert into sheet_results values('inactive positioned player denied',denied);
 reset role;
 -- Membership in a different club cannot revive historical selection access.
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(d,pa,'member',true);
 set local role authenticated;
 denied:=false;
 begin perform public.get_authorized_team_sheet_data(f); exception when raise_exception then denied:=sqlerrm='Not authorised to view this team sheet.'; end;
 insert into sheet_results values('active membership in different club insufficient',denied);
 reset role;
 delete from public.club_memberships where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false;
 begin perform public.get_authorized_team_sheet_data(f); exception when raise_exception then denied:=sqlerrm='Not authorised to view this team sheet.'; end;
 insert into sheet_results values('removed membership denied',denied);
 reset role;
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(c,pa,'member',true);
 update public.team_selections set status='draft' where id=s;
 set local role authenticated;
 denied:=false;
 begin perform public.get_authorized_team_sheet_data(f); exception when raise_exception then denied:=sqlerrm='Not authorised to view this team sheet.'; end;
 insert into sheet_results values('ordinary player cannot view draft',denied);
 reset role;
 update public.club_memberships set role='admin' where club_id=c and member_profile_id=pa;
 set local role authenticated;
 j:=public.get_authorized_team_sheet_data(f);
 insert into sheet_results values('active admin can view draft',j#>>'{access,selection_status}'='draft');
 reset role;
 update public.club_memberships set is_active=false where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false;
 begin perform public.get_authorized_team_sheet_data(f); exception when raise_exception then denied:=sqlerrm='Not authorised to view this team sheet.'; end;
 insert into sheet_results values('inactive admin denied',denied);
 reset role;
 insert into public.app_superusers(user_id) values(a);
 set local role authenticated;
 j:=public.get_authorized_team_sheet_data(g);
 insert into sheet_results values('superuser retains cross club draft access',j#>>'{fixture,id}'=g::text and j#>>'{access,can_manage}'='true');
 reset role;
 delete from public.app_superusers where user_id=a;
 perform set_config('request.jwt.claims','{}',true);
 set local role authenticated;
 denied:=false;
 begin perform public.get_authorized_team_sheet_data(f); exception when raise_exception then denied:=sqlerrm='Not authorised to view this team sheet.'; end;
 insert into sheet_results values('missing identity denied',denied);
 reset role;
 set local role anon;
 denied:=false;
 begin perform public.get_authorized_team_sheet_data(f); exception when insufficient_privilege then denied:=true; end;
 insert into sheet_results values('anonymous execute denied',denied);
 reset role;
 insert into sheet_results values('cron remains disabled',not exists(select 1 from cron.job where active));
 if exists(select 1 from sheet_results where not passed) then raise exception 'Team sheet tests failed'; end if;
end $$;
select * from sheet_results order by test;
rollback;

