begin;
set local statement_timeout='25s';
create temp table trigger_results(test text,passed boolean) on commit drop;
grant insert,select on trigger_results to authenticated,anon;
do $$
declare
 c uuid:=gen_random_uuid(); d uuid:=gen_random_uuid();
 a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); pa uuid; pb uuid;
 v uuid; w uuid; f uuid; g uuid; h uuid; s uuid; t uuid; u uuid;
 denied boolean; n bigint; baseline bigint; x uuid:=gen_random_uuid(); px uuid; extra_club uuid; vr uuid;
begin
 if exists(select 1 from cron.job where active) then raise exception 'Disable cron before test'; end if;
 select count(*) into baseline from public.notification_queue;
 insert into public.clubs(id,name) values(c,'ROLLBACK publication own'),(d,'ROLLBACK publication foreign');
 insert into auth.users(id,email,raw_user_meta_data,raw_app_meta_data) values
 (a,a::text||'@example.invalid','{"display_name":"Publication admin"}','{}'),
 (b,b::text||'@example.invalid','{"display_name":"Publication foreign reserve"}','{}');
 select id into pa from public.member_profiles where user_id=a;
 select id into pb from public.member_profiles where user_id=b;
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(c,pa,'admin',true),(d,pb,'member',true);
 insert into public.venues(club_id,name,is_home_venue) values(c,'Rollback own venue',false) returning id into v;
 insert into public.venues(club_id,name,is_home_venue) values(d,'Rollback foreign venue',false) returning id into w;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '30 days',false,v,1,4) returning id into f;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '31 days',false,v,1,4) returning id into h;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(d,now()+interval '32 days',false,w,1,4) returning id into g;
 insert into public.team_selections(fixture_id) values(f) returning id into s;
 insert into public.team_selections(fixture_id) values(g) returning id into t;
 insert into public.team_selections(fixture_id) values(h) returning id into u;
 insert into public.team_selection_members(team_selection_id,member_profile_id,role,is_selected) values(s,pa,'reserve',true),(t,pb,'reserve',true);
 insert into auth.users(id,email,raw_user_meta_data,raw_app_meta_data) values(x,x::text||'@example.invalid','{"display_name":"Trigger profile test","role":"admin","is_superuser":true}','{}');
 select id into px from public.member_profiles where user_id=x;
 insert into trigger_results select 'signup trigger creates own profile',count(*)=1 and bool_and(display_name='Trigger profile test') from public.member_profiles where user_id=x;
 insert into trigger_results values('signup metadata does not grant superuser',not exists(select 1 from public.app_superusers where user_id=x));
 insert into trigger_results values('signup metadata does not grant club membership',not exists(select 1 from public.club_memberships where member_profile_id=px));
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 insert into public.clubs(name,created_by) values('Rollback creator trigger',b) returning id into extra_club;
 insert into trigger_results select 'club creator overwritten with caller',created_by=a from public.clubs where id=extra_club;
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(c,pb,'member',true),(c,px,'member',true);
 update public.fixtures set captain_member_profile_id=pb where id=f;
 update public.team_selections set status='published' where id=s;
 set local role authenticated;
 update public.team_selection_members set acceptance='accepted' where team_selection_id=s and member_profile_id=pa;
 get diagnostics n=row_count;
 insert into trigger_results values('own acceptance update permitted',n=1);
 reset role;
 insert into trigger_results select 'acceptance trigger targets own fixture captain',count(*)=1 and bool_and(target_member_profile_id=pb and member_profile_id=pa and payload->>'new_acceptance'='accepted') from public.notification_queue where fixture_id=f and event_type='team_acceptance_changed';
 set local role authenticated;
 update public.team_selection_members set acceptance='declined' where team_selection_id=s and member_profile_id=pa;
 reset role;
 insert into trigger_results select 'pending acceptance updates coalesced',count(*)=1 and bool_and(payload->>'new_acceptance'='declined') from public.notification_queue where fixture_id=f and event_type='team_acceptance_changed';
 perform set_config('request.jwt.claims',jsonb_build_object('sub',x,'role','authenticated')::text,true);
 set local role authenticated;
 update public.team_selection_members set acceptance='accepted' where team_selection_id=s and member_profile_id=pa;
 get diagnostics n=row_count;
 insert into trigger_results values('unrelated member cannot fire acceptance trigger for another player',n=0);
 reset role;
 insert into trigger_results select 'unauthorized acceptance unchanged',acceptance='declined' from public.team_selection_members where team_selection_id=s and member_profile_id=pa;
 insert into public.club_member_volunteer_roles(club_id,member_profile_id,volunteer_role) values(c,pa,'marker') returning id into vr;
 set local role authenticated;
 denied:=false; begin delete from public.marker_volunteer_directory where volunteer_role_id=vr; exception when insufficient_privilege then denied:=true; end;
 insert into trigger_results values('authenticated cannot reach volunteer delete trigger',denied);
 denied:=false; begin perform public.handle_new_user(); exception when feature_not_supported then denied:=true; end; insert into trigger_results values('authenticated cannot directly call handle_new_user',denied);
 denied:=false; begin perform public.set_club_created_by(); exception when feature_not_supported then denied:=true; end; insert into trigger_results values('authenticated cannot directly call set_club_created_by',denied);
 denied:=false; begin perform public.queue_team_acceptance_change(); exception when feature_not_supported then denied:=true; end; insert into trigger_results values('authenticated cannot directly call queue_team_acceptance_change',denied);
 denied:=false; begin perform public.delete_marker_volunteer_from_view(); exception when feature_not_supported then denied:=true; end; insert into trigger_results values('authenticated cannot directly call delete_marker_volunteer_from_view',denied);
 reset role;
 set local role anon;
 denied:=false; begin delete from public.marker_volunteer_directory where volunteer_role_id=vr; exception when insufficient_privilege then denied:=true; end;
 insert into trigger_results values('anon cannot reach volunteer delete trigger',denied);
 denied:=false; begin perform public.handle_new_user(); exception when feature_not_supported then denied:=true; end; insert into trigger_results values('anon cannot directly call handle_new_user',denied);
 denied:=false; begin perform public.set_club_created_by(); exception when feature_not_supported then denied:=true; end; insert into trigger_results values('anon cannot directly call set_club_created_by',denied);
 denied:=false; begin perform public.queue_team_acceptance_change(); exception when feature_not_supported then denied:=true; end; insert into trigger_results values('anon cannot directly call queue_team_acceptance_change',denied);
 denied:=false; begin perform public.delete_marker_volunteer_from_view(); exception when feature_not_supported then denied:=true; end; insert into trigger_results values('anon cannot directly call delete_marker_volunteer_from_view',denied);
 reset role;
 perform set_config('request.jwt.claims','{"role":"service_role"}',true);
 set local role service_role;
 delete from public.marker_volunteer_directory where volunteer_role_id=vr;
 reset role;
 insert into trigger_results select 'server volunteer deletion works',not exists(select 1 from public.club_member_volunteer_roles where id=vr);
 insert into trigger_results values('cron remains disabled',not exists(select 1 from cron.job where active));
 if exists(select 1 from trigger_results where not passed) then raise exception 'Trigger checks failed'; end if;
end $$;
select * from trigger_results order by test;
rollback;
