begin;
set local statement_timeout='25s';
create temp table move_results(test text,passed boolean) on commit drop;
grant insert,select on move_results to authenticated,anon;
do $$
declare
 c uuid:=gen_random_uuid(); d uuid:=gen_random_uuid();
 a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); pa uuid; pb uuid;
 v uuid; w uuid; f uuid; g uuid; h uuid; s uuid; t uuid; u uuid;
 denied boolean; n bigint; baseline bigint; r uuid; old_start timestamptz:=now()+interval '20 days'; old_end timestamptz:=now()+interval '20 days 2 hours';
begin
 if exists(select 1 from cron.job where active) then raise exception 'Disable cron before test'; end if;
 select count(*) into baseline from public.notification_queue;
 insert into public.clubs(id,name) values(c,'ROLLBACK publication own'),(d,'ROLLBACK publication foreign');
 insert into auth.users(id,email,raw_user_meta_data,raw_app_meta_data) values
 (a,a::text||'@example.invalid','{"display_name":"Publication admin"}','{}'),
 (b,b::text||'@example.invalid','{"display_name":"Publication foreign reserve"}','{}');
 select id into pa from public.member_profiles where user_id=a;
 select id into pb from public.member_profiles where user_id=b;
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(c,pa,'admin',true),(d,pb,'member',true);
 insert into public.venues(club_id,name,is_home_venue) values(c,'Rollback own venue',false) returning id into v;
 insert into public.venues(club_id,name,is_home_venue) values(d,'Rollback foreign venue',false) returning id into w;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '30 days',false,v,1,4) returning id into f;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '31 days',false,v,1,4) returning id into h;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(d,now()+interval '32 days',false,w,1,4) returning id into g;
 insert into public.team_selections(fixture_id) values(f) returning id into s;
 insert into public.team_selections(fixture_id) values(g) returning id into t;
 insert into public.team_selections(fixture_id) values(h) returning id into u;
 insert into public.team_selection_members(team_selection_id,member_profile_id,role,is_selected) values(s,pa,'reserve',true),(t,pb,'reserve',true);
 insert into public.fixture_rinks(fixture_id,fixture_rink_no,format,players_per_rink) values(f,1,'rinks',4) returning id into r;
 insert into public.fixture_rink_assignments(fixture_id,fixture_rink_id,member_profile_id,position) values(f,r,pa,1);

 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 n:=public.queue_fixture_moved_notifications(f,old_start,old_end);
 insert into move_results values('first move queues one',n=1);
 n:=public.queue_fixture_moved_notifications(f,old_start,old_end);
 insert into move_results values('repeat move queues none',n=0);
 set local timezone='America/New_York';
 n:=public.queue_fixture_moved_notifications(f,old_start,old_end);
 insert into move_results values('same instants in another timezone deduplicated',n=0);
 set local timezone='UTC';
 n:=public.queue_fixture_moved_notifications(f,old_start+interval '1 day',old_end+interval '1 day');
 insert into move_results values('different old schedule queues one',n=1);
 n:=public.queue_fixture_moved_notifications(f,old_start+interval '2 days',null);
 insert into move_results values('null old end supported',n=1);
 n:=public.queue_fixture_moved_notifications(f,old_start+interval '2 days',null);
 insert into move_results values('null old end deduplicated',n=0);
 reset role;
 update public.notification_queue set status='sent' where fixture_id=f and event_type='fixture_moved';
 set local role authenticated;
 n:=public.queue_fixture_moved_notifications(f,old_start,old_end);
 insert into move_results values('already sent move not repeated',n=0);
 reset role;
 update public.fixtures set start_at=start_at+interval '1 day' where id=f;
 set local role authenticated;
 n:=public.queue_fixture_moved_notifications(f,old_start,old_end);
 insert into move_results values('different new schedule queues one',n=1);
 reset role;
 update public.club_memberships set role='member',is_active=true where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false; begin perform public.queue_fixture_moved_notifications(f,old_start,old_end); exception when raise_exception then denied:=sqlerrm='You do not have permission to queue fixture-move notifications.'; end;
 insert into move_results values('member denied',denied);
 reset role;
 update public.club_memberships set role='guest',is_active=true where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false; begin perform public.queue_fixture_moved_notifications(f,old_start,old_end); exception when raise_exception then denied:=sqlerrm='You do not have permission to queue fixture-move notifications.'; end;
 insert into move_results values('guest denied',denied);
 reset role;
 update public.club_memberships set role='admin',is_active=false where club_id=c and member_profile_id=pa;
 set local role authenticated;
 denied:=false; begin perform public.queue_fixture_moved_notifications(f,old_start,old_end); exception when raise_exception then denied:=sqlerrm='You do not have permission to queue fixture-move notifications.'; end;
 insert into move_results values('inactive admin denied',denied);
 reset role; update public.club_memberships set role='admin',is_active=true where club_id=c and member_profile_id=pa; set local role authenticated;
 denied:=false; begin perform public.queue_fixture_moved_notifications(g,old_start,old_end); exception when raise_exception then denied:=sqlerrm='You do not have permission to queue fixture-move notifications.'; end;
 insert into move_results values('foreign fixture denied',denied);
 reset role; insert into public.app_superusers(user_id) values(a); set local role authenticated;
 n:=public.queue_fixture_moved_notifications(g,old_start,old_end);
 insert into move_results values('superuser foreign empty fixture allowed',n=0);
 reset role; perform set_config('request.jwt.claims','{}',true); set local role authenticated;
 denied:=false; begin perform public.queue_fixture_moved_notifications(f,old_start,old_end); exception when raise_exception then denied:=sqlerrm='You do not have permission to queue fixture-move notifications.'; end;
 insert into move_results values('missing identity denied',denied);
 reset role; set local role anon;
 denied:=false; begin perform public.queue_fixture_moved_notifications(f,old_start,old_end); exception when insufficient_privilege then denied:=true; end;
 insert into move_results values('anonymous execute denied',denied);
 reset role;
 insert into move_results select 'only intended recipient queued',count(*)=4 and bool_and(target_member_profile_id=pa) from public.notification_queue where fixture_id=f and event_type='fixture_moved';
 insert into move_results values('cron remains disabled',not exists(select 1 from cron.job where active));
 if exists(select 1 from move_results where not passed) then raise exception 'Move checks failed'; end if;
end $$;
select * from move_results order by test;
rollback;
