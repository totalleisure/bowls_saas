begin;
set local statement_timeout='25s';
create temp table opponent_results(test text,passed boolean) on commit drop;
grant insert,select on opponent_results to authenticated,anon;
do $$
declare
 c uuid:=gen_random_uuid(); d uuid:=gen_random_uuid();
 a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); pa uuid; pb uuid;
 v uuid; w uuid; f uuid; g uuid; h uuid; s uuid; t uuid; u uuid;
 denied boolean; n bigint; baseline bigint;
begin
 if exists(select 1 from cron.job where active) then raise exception 'Disable cron before test'; end if;
 select count(*) into baseline from public.notification_queue;
 insert into public.clubs(id,name) values(c,'ROLLBACK publication own'),(d,'ROLLBACK publication foreign');
 insert into auth.users(id,email,raw_user_meta_data,raw_app_meta_data) values
 (a,a::text||'@example.invalid','{"display_name":"Publication admin"}','{}'),
 (b,b::text||'@example.invalid','{"display_name":"Publication foreign reserve"}','{}');
 select id into pa from public.member_profiles where user_id=a;
 select id into pb from public.member_profiles where user_id=b;
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(c,pa,'admin',true),(d,pb,'member',true);
 insert into public.venues(club_id,name,is_home_venue) values(c,'Rollback own venue',false) returning id into v;
 insert into public.venues(club_id,name,is_home_venue) values(d,'Rollback foreign venue',false) returning id into w;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '30 days',false,v,1,4) returning id into f;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(c,now()+interval '31 days',false,v,1,4) returning id into h;
 insert into public.fixtures(club_id,start_at,is_home,venue_id,rinks_required,players_per_rink) values(d,now()+interval '32 days',false,w,1,4) returning id into g;
 insert into public.team_selections(fixture_id) values(f) returning id into s;
 insert into public.team_selections(fixture_id) values(g) returning id into t;
 insert into public.team_selections(fixture_id) values(h) returning id into u;
 insert into public.team_selection_members(team_selection_id,member_profile_id,role,is_selected) values(s,pa,'reserve',true),(t,pb,'reserve',true);
 insert into public.club_memberships(club_id,member_profile_id,role,is_active) values(c,pb,'member',true);
 insert into public.team_selection_members(team_selection_id,member_profile_id,role,is_selected) values(s,pb,'reserve',true);
 update public.team_selections set status='published' where id=s;

 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 denied:=false; begin perform public.queue_fixture_opponent_changed_notifications(f,v,w); exception when sqlstate '22023' then denied:=true; end;
 insert into opponent_results values('foreign new venue rejected',denied);
 denied:=false; begin perform public.queue_fixture_opponent_changed_notifications(f,w,v); exception when sqlstate '22023' then denied:=true; end;
 insert into opponent_results values('foreign old venue rejected',denied);
 denied:=false; begin perform public.queue_fixture_opponent_changed_notifications(f,v,gen_random_uuid()); exception when sqlstate '22023' then denied:=true; end;
 insert into opponent_results values('unknown new venue rejected',denied);
 denied:=false; begin perform public.queue_fixture_opponent_changed_notifications(f,gen_random_uuid(),v); exception when sqlstate '22023' then denied:=true; end;
 insert into opponent_results values('unknown old venue rejected',denied);
 reset role;
 insert into opponent_results select 'invalid venues leave queue unchanged',count(*)=baseline from public.notification_queue;
 set local role authenticated;
 n:=public.queue_fixture_opponent_changed_notifications(f,null,v);
 insert into opponent_results values('own venue change queues recipient',n=1);
 reset role;
 insert into opponent_results select 'queued payload uses own venue',count(*)=1 and bool_and(payload->>'new_opponent_name'='Rollback own venue' and member_profile_id=pa and target_member_profile_id=pb) from public.notification_queue where fixture_id=f and event_type='fixture_opponent_changed';
 set local role authenticated;
 n:=public.queue_fixture_opponent_changed_notifications(h,v,null);
 insert into opponent_results values('draft fixture does not notify',n=0);
 n:=public.queue_fixture_opponent_changed_notifications(f,v,null);
 insert into opponent_results values('clearing opponent supported',n=1);
 reset role; update public.club_memberships set role='member',is_active=true where club_id=c and member_profile_id=pa; set local role authenticated;
 denied:=false; begin perform public.queue_fixture_opponent_changed_notifications(f,null,v); exception when raise_exception then denied:=sqlerrm='You do not have permission to queue opponent-change notifications.'; end;
 insert into opponent_results values('member denied',denied);
 reset role; update public.club_memberships set role='admin',is_active=false where club_id=c and member_profile_id=pa; set local role authenticated;
 denied:=false; begin perform public.queue_fixture_opponent_changed_notifications(f,null,v); exception when raise_exception then denied:=sqlerrm='You do not have permission to queue opponent-change notifications.'; end;
 insert into opponent_results values('inactive admin denied',denied);
 reset role; update public.club_memberships set role='guest',is_active=true where club_id=c and member_profile_id=pa; set local role authenticated;
 denied:=false; begin perform public.queue_fixture_opponent_changed_notifications(f,null,v); exception when raise_exception then denied:=sqlerrm='You do not have permission to queue opponent-change notifications.'; end;
 insert into opponent_results values('guest denied',denied);
 reset role; update public.club_memberships set role='admin',is_active=true where club_id=c and member_profile_id=pa; set local role authenticated;
 denied:=false; begin perform public.queue_fixture_opponent_changed_notifications(g,null,w); exception when raise_exception then denied:=sqlerrm='You do not have permission to queue opponent-change notifications.'; end;
 insert into opponent_results values('foreign fixture denied',denied);
 reset role; insert into public.app_superusers(user_id) values(a); set local role authenticated;
 denied:=false; begin perform public.queue_fixture_opponent_changed_notifications(f,null,w); exception when sqlstate '22023' then denied:=true; end;
 insert into opponent_results values('superuser venue binding retained',denied);
 n:=public.queue_fixture_opponent_changed_notifications(g,null,w);
 insert into opponent_results values('superuser foreign draft fixture allowed',n=0);
 reset role; perform set_config('request.jwt.claims','{}',true);
 set local role authenticated;
 denied:=false; begin perform public.queue_fixture_opponent_changed_notifications(f,null,v); exception when raise_exception then denied:=sqlerrm='You do not have permission to queue opponent-change notifications.'; end;
 insert into opponent_results values('authenticated missing identity denied',denied);
 reset role;
 set local role anon;
 denied:=false; begin perform public.queue_fixture_opponent_changed_notifications(f,null,v); exception when raise_exception then denied:=sqlerrm='You do not have permission to queue opponent-change notifications.'; end;
 insert into opponent_results values('anon missing identity denied',denied);
 reset role;
 insert into opponent_results values('cron remains disabled',not exists(select 1 from cron.job where active));
 if exists(select 1 from opponent_results where not passed) then raise exception 'Opponent checks failed'; end if;
end $$;
select * from opponent_results order by test;
rollback;
